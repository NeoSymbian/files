//! Compiles the screens with the neoui kit (`@neoui`): glyphs and images baked in, SDF text. For the documents (FA10)
//! it also writes, into OUT_DIR, the characters documents may use as a hidden Slint text (`@files-gen/glyphs.slint`:
//! Slint bakes only the glyphs its literals use) and their advances in the four document faces (`advances.rs`), so
//! the Rust layout measures exactly what Slint draws without carrying the fonts twice. The document faces are
//! DejaVu Sans renamed "NeoDoc" (ui/fonts/NeoDoc.license), so the app's other "DejaVu Sans" text keeps one face.
use std::fmt::Write as _;
use std::path::PathBuf;

/// What a document can show: Latin-1 and Extended-A, Greek, Cyrillic, Armenian, punctuation, currency, a few signs.
const RANGES: &[(u32, u32)] = &[
    (0x20, 0x7e),
    (0xa0, 0x17f),
    (0x192, 0x192),
    (0x2c6, 0x2c7),
    (0x2d8, 0x2dd),
    (0x370, 0x3ff),
    (0x400, 0x4ff),
    (0x531, 0x58a),
    (0x2010, 0x2027),
    (0x2030, 0x203a),
    (0x2044, 0x2044),
    (0x20a0, 0x20bf),
    (0x2116, 0x2116),
    (0x2122, 0x2122),
    (0x2190, 0x2193),
    (0x2212, 0x2212),
    (0x25a1, 0x25a1),
    (0x25cb, 0x25cf),
    (0x2713, 0x2713),
];

fn main() {
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let fonts = neoui_kit::ui_dir().join("fonts");
    let own = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("ui/fonts");
    let files = [
        own.join("NeoDoc-Regular.ttf"),
        own.join("NeoDoc-Bold.ttf"),
        own.join("NeoDoc-Oblique.ttf"),
        fonts.join("DejaVuSansMono.ttf"),
    ];
    let data: Vec<Vec<u8>> = files
        .iter()
        .map(|f| std::fs::read(f).unwrap_or_else(|e| panic!("{}: {e}", f.display())))
        .collect();
    let faces: Vec<ttf_parser::Face> = data
        .iter()
        .map(|d| ttf_parser::Face::parse(d, 0).unwrap())
        .collect();
    // a character every sans face has (else Slint would bake it from the build machine's fonts)
    let chars: Vec<char> = RANGES
        .iter()
        .flat_map(|&(a, b)| a..=b)
        .filter_map(char::from_u32)
        .filter(|&c| faces[..3].iter().all(|f| f.glyph_index(c).is_some()))
        .collect();

    let mut slint = String::from(
        "// generated by files-ui's build.rs: every character a document may show, so that Slint bakes its glyphs\n\
         export component DocGlyphs inherits Text {\n    visible: false;\n    font-family: \"NeoDoc\";\n    text: \"",
    );
    for c in &chars {
        match c {
            '"' => slint.push_str("\\\""),
            '\\' => slint.push_str("\\\\"),
            c => slint.push(*c),
        }
    }
    slint.push_str("\";\n}\n");
    std::fs::write(out.join("glyphs.slint"), slint).unwrap();

    // (char, advance per face in font units (0xffff: no glyph), whether each face's glyph has ink)
    let mut rs = String::new();
    let upem: Vec<u16> = faces.iter().map(|f| f.units_per_em()).collect();
    let asc: Vec<i16> = faces.iter().map(|f| f.ascender()).collect();
    writeln!(
        rs,
        "/// Units per em of Regular, Bold, Oblique, Mono.\npub const UPEM: [u16; 4] = {upem:?};"
    )
    .unwrap();
    writeln!(
        rs,
        "/// Ascenders (hhea), font units.\npub const ASCENT: [i16; 4] = {asc:?};"
    )
    .unwrap();
    writeln!(rs, "/// Sorted by char: advances (0xffff = none) and a bit per face for glyphs with an outline.").unwrap();
    writeln!(
        rs,
        "pub static ADVANCES: [(char, [u16; 4], u8); {}] = [",
        chars.len()
    )
    .unwrap();
    for c in &chars {
        let mut adv = [0xffffu16; 4];
        let mut ink = 0u8;
        for (i, f) in faces.iter().enumerate() {
            if let Some(g) = f.glyph_index(*c) {
                adv[i] = f.glyph_hor_advance(g).unwrap_or(0);
                if f.glyph_bounding_box(g).is_some() {
                    ink |= 1 << i;
                }
            }
        }
        writeln!(rs, "    ({c:?}, {adv:?}, {ink}),").unwrap();
    }
    rs.push_str("];\n");
    std::fs::write(out.join("advances.rs"), rs).unwrap();

    neoui_kit::compile_with("ui/files.slint", &[("files-gen", out)]);
    println!("cargo:rerun-if-changed=ui/fonts");
}
